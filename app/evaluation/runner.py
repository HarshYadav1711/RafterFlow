"""Black-box Appendix F evaluation runner (HTTP client only)."""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Callable
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

from app.clock import reference_now
from app.evaluation.appendix_f import APPENDIX_F_CASES, EvalCase
from app.evaluation.invariants import CheckResult, evaluate_case, note_for_checks


class EvalRunError(RuntimeError):
    """Raised when the evaluation cannot complete honestly (HTTP/infra failure)."""


HttpPost = Callable[[str, dict[str, Any], float], dict[str, Any]]


@dataclass
class CaseResult:
    case: EvalCase
    http_status: int
    response: dict[str, Any]
    checks: list[CheckResult] = field(default_factory=list)
    note: str = "None."


def default_http_post(url: str, payload: dict[str, Any], timeout: float) -> dict[str, Any]:
    body = json.dumps(payload).encode("utf-8")
    req = Request(
        url,
        data=body,
        headers={"Content-Type": "application/json", "Accept": "application/json"},
        method="POST",
    )
    try:
        with urlopen(req, timeout=timeout) as resp:  # noqa: S310 — local eval target
            raw = resp.read().decode("utf-8")
            status = getattr(resp, "status", 200)
            data = json.loads(raw) if raw else {}
            data["_http_status"] = status
            return data
    except HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise EvalRunError(
            f"HTTP {exc.code} from {url}: {detail[:500]}"
        ) from exc
    except URLError as exc:
        raise EvalRunError(f"Could not reach {url}: {exc.reason}") from exc
    except json.JSONDecodeError as exc:
        raise EvalRunError(f"Non-JSON response from {url}") from exc


def build_payload(case: EvalCase, received_at: datetime) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "channel": "whatsapp",
        "from_phone": case.phone,
        "message": case.message,
        "received_at": received_at.isoformat(),
    }
    if case.from_name is not None:
        payload["from_name"] = case.from_name
    return payload


def render_eval_md(results: list[CaseResult], *, base_url: str) -> str:
    lines: list[str] = [
        "# Appendix F evaluation results",
        "",
        f"Generated by `run_eval.py` against `{base_url}`.",
        "",
        "Checks are objective invariants from the assessment. "
        "Notes are honest when a check fails.",
        "",
    ]
    for item in results:
        lead = item.response.get("lead") or {}
        tools = item.response.get("tool_calls") or []
        lines.extend(
            [
                f"## Case {item.case.case_id} — {item.case.name}",
                "",
                f"- **Phone:** `{item.case.phone}`",
                f"- **Message:** {item.case.message}",
                f"- **HTTP status:** {item.http_status}",
                f"- **Final lead status:** `{lead.get('status')}`",
                f"- **Lead id:** `{lead.get('lead_id')}`",
                "",
                "### Agent reply",
                "",
                item.response.get("reply") or "(empty)",
                "",
                "### Tool calls",
                "",
                "```json",
                json.dumps(tools, indent=2, ensure_ascii=True),
                "```",
                "",
                "### Automated checks",
                "",
            ]
        )
        if not item.checks:
            lines.append("- (no automated checks defined)")
        else:
            for check in item.checks:
                mark = "PASS" if check.passed else "FAIL"
                suffix = f" — {check.detail}" if check.detail and not check.passed else ""
                lines.append(f"- {mark} {check.label}{suffix}")
        lines.extend(["", f"**Note:** {item.note}", ""])
    return "\n".join(lines) + "\n"


def run_evaluation(
    *,
    base_url: str = "http://127.0.0.1:8000",
    output_path: str | Path = "eval.md",
    timeout: float = 120.0,
    http_post: HttpPost | None = None,
    received_at: datetime | None = None,
    cases: tuple[EvalCase, ...] | None = None,
) -> list[CaseResult]:
    """
    Send every Appendix F message in order to POST /enquiries and write eval.md.

    HTTP-only: does not reset or otherwise mutate the application database.
    Does not use admin credentials. Does not call the LLM directly.
    Expects the target service to already be on a fresh Appendix-seeded baseline.
    """
    post = http_post or default_http_post
    eval_cases = cases if cases is not None else APPENDIX_F_CASES
    when = received_at if received_at is not None else reference_now()
    endpoint = base_url.rstrip("/") + "/enquiries"

    results: list[CaseResult] = []
    previous_response: dict[str, Any] | None = None

    for case in eval_cases:
        payload = build_payload(case, when)
        raw = post(endpoint, payload, timeout)
        http_status = int(raw.pop("_http_status", 200))
        checks = evaluate_case(case.case_id, raw, previous_response)
        note = note_for_checks(checks)
        results.append(
            CaseResult(
                case=case,
                http_status=http_status,
                response=raw,
                checks=checks,
                note=note,
            )
        )
        previous_response = raw

    path = Path(output_path)
    path.write_text(render_eval_md(results, base_url=base_url), encoding="utf-8")
    return results


def resolve_base_url(cli_value: str | None = None) -> str:
    if cli_value:
        return cli_value
    return os.getenv("EVAL_BASE_URL", "http://127.0.0.1:8000")
